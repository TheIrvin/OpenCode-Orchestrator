<#
.SYNOPSIS
  Install the ORQUESTADOR system into OpenCode's global configuration.

.DESCRIPTION
  Copies agents, commands, skills and plugins to ~/.config/opencode/ and generates
  a global configuration from opencode.jsonc. It also:

    - Rewrites the MCP memory file path to an absolute location.
    - Creates the global error store (~/.config/opencode/orquestador/) and
      registers its rules in `instructions` so they load in the cached prompt
      prefix (no tool calls or reasoning spent).
    - Installs the model manifest (`models.json`) with families and fallback
      chains, used by the `model-fallback` plugin to rotate when a model is
      exhausted.

  It does not touch service.json or destroy previous configuration: if a global
  opencode.json(c) already exists, it backs it up before writing.

.EXAMPLE
  pwsh -File install.ps1
#>

[CmdletBinding()]
param(
  [string]$Destination = (Join-Path $env:USERPROFILE ".config\opencode")
)

$ErrorActionPreference = "Stop"
$Source = $PSScriptRoot

Write-Host "ORQUESTADOR -> $Destination" -ForegroundColor Cyan

# 1. Directories
$store = Join-Path $Destination "orquestador"
$dirs = @(
  $Destination,
  (Join-Path $Destination "agents"),
  (Join-Path $Destination "commands"),
  (Join-Path $Destination "skills"),
  (Join-Path $Destination "plugins"),
  (Join-Path $Destination "memory"),
  $store
)
foreach ($dir in $dirs) {
  New-Item -ItemType Directory -Force -Path $dir | Out-Null
}

# 2. Agents, commands, skills and plugins
foreach ($sub in @("agents", "commands", "skills", "plugins")) {
  $from = Join-Path $Source ".opencode\$sub"
  if (Test-Path $from) {
    Copy-Item -Path (Join-Path $from "*") -Destination (Join-Path $Destination $sub) -Recurse -Force
    Write-Host "  [ok] .opencode\$sub" -ForegroundColor Green
  }
}

# 3. Global error store (rules + digest)
$rules = Join-Path $store "rules.md"
if (-not (Test-Path $rules)) {
  Copy-Item (Join-Path $Source "orquestador\rules.md") $rules
  Write-Host "  [ok] orquestador\rules.md" -ForegroundColor Green
} else {
  Write-Host "  [i] orquestador\rules.md already exists, your rules are preserved" -ForegroundColor Yellow
}
$auto = Join-Path $store "auto.md"
$jsonl = Join-Path $store "errors.jsonl"
if (-not (Test-Path $auto))  { [System.IO.File]::WriteAllText($auto,  "<!-- Generated by error-memory. Do not edit by hand. -->`n# Recurring errors (auto)`n`n- (no recorded errors)`n", (New-Object System.Text.UTF8Encoding($false))) }
if (-not (Test-Path $jsonl)) { [System.IO.File]::WriteAllText($jsonl, "", (New-Object System.Text.UTF8Encoding($false))) }

# 3b. Model manifest + fallback chains (single source for the fallback)
Copy-Item (Join-Path $Source "orquestador\models.json") (Join-Path $store "models.json") -Force
Write-Host "  [ok] orquestador\models.json (families + per-role chains)" -ForegroundColor Green
$cooldown = Join-Path $store "model-cooldown.json"
if (-not (Test-Path $cooldown)) { [System.IO.File]::WriteAllText($cooldown, "{}`n", (New-Object System.Text.UTF8Encoding($false))) }

# 4. Global configuration (absolute paths + cached instructions)
$globalConfig = Join-Path $Destination "opencode.jsonc"
if (Test-Path $globalConfig) {
  $stamp = Get-Date -Format "yyyyMMdd-HHmmss"
  Copy-Item $globalConfig "$globalConfig.bak-$stamp"
  Write-Host "  [i] backup: opencode.jsonc.bak-$stamp" -ForegroundColor Yellow
}
$memoryFile = (Join-Path $Destination "memory\graph.jsonl") -replace "\\", "\\"
$rulesJson = $rules -replace "\\", "\\"
$autoJson = $auto -replace "\\", "\\"
$content = Get-Content (Join-Path $Source "opencode.jsonc") -Raw
$content = $content.Replace(".orquestador/memory/graph.jsonl", $memoryFile)
$anchor = '"$schema": "https://opencode.ai/config.json",'
$instructions = $anchor + "`n  `"instructions`": [`"$rulesJson`", `"$autoJson`"],"
if ($content.Contains($anchor)) {
  $content = $content.Replace($anchor, $instructions)
  Write-Host "  [ok] instructions (rules in the cached prompt)" -ForegroundColor Green
} else {
  Write-Host "  [!] could not find the `$schema anchor; set instructions manually" -ForegroundColor Yellow
}
# UTF-8 WITHOUT BOM (PS 5.1's Set-Content -Encoding UTF8 adds a BOM, which breaks the JSON)
[System.IO.File]::WriteAllText($globalConfig, $content, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "  [ok] opencode.jsonc (global)" -ForegroundColor Green

# 5. Global instructions (only if they don't exist)
$globalAgents = Join-Path $Destination "AGENTS.md"
if (-not (Test-Path $globalAgents)) {
  Copy-Item (Join-Path $Source "global\AGENTS.md") $globalAgents
  Write-Host "  [ok] AGENTS.md (global)" -ForegroundColor Green
} else {
  Write-Host "  [i] global AGENTS.md already exists, left untouched" -ForegroundColor Yellow
}

Write-Host ""
Write-Host "Done. In OpenCode:" -ForegroundColor Cyan
Write-Host "  - Default primary agent: orchestrator"
Write-Host "  - Commands: /orq /plan-quick /plan-deep /plan-long /build /review /research /catalogo /memory-init /errores /modelos"
Write-Host "  - Errors are logged to $store (never inside your projects)"
Write-Host "  - The rules load on their own into the prompt; no need to read them"
Write-Host "  - If a model is exhausted, the model-fallback plugin rotates to the next family"
Write-Host "  - Run /mcps to sign in to context7 and check the MCP memory"
