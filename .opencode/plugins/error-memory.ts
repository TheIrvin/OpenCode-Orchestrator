/**
 * error-memory — error persistence WITHOUT leaving files in the project.
 *
 * Writes EVERYTHING to a global store (
 *   ~/.config/opencode/orquestador/ ), never inside the user's repository:
 *
 *   errors.jsonl  → full log (append-only, with the source project)
 *   auto.md       → digest of recurrent errors (≤15 lines), loaded by
 *                   `instructions` as part of the cached prompt
 *
 * The goal is twofold:
 *   1. That an error does not repeat (it stays recorded and, the recurrent
 *      ones, visible to the model without spending tool calls).
 *   2. Not to dirty any project with files that could end up in a commit.
 *
 * `auto.md` is only rewritten when its content changes, so as not to invalidate
 * the prompt cache without reason.
 *
 * A failure arrives in two ways:
 *   - `status: "error"` (hard tool error).
 *   - `status: "completed"` with `result.output.exit !== 0` (shell command
 *     that finished with a non-zero code: the typical quotes/paths case).
 *
 * No need for `@opencode/plugin`: the V2 loader reads the `id` and `setup()` from
 * the default export. Never throws: if something fails, it is ignored.
 */

import { appendFile, mkdir, readFile, writeFile } from "node:fs/promises"
import { createHash } from "node:crypto"
import { homedir } from "node:os"
import path from "node:path"

const STORE =
  process.env.ORQUESTADOR_STORE || path.join(homedir(), ".config", "opencode", "orquestador")
const JSONL = path.join(STORE, "errors.jsonl")
const AUTO = path.join(STORE, "auto.md")
const MAX_AUTO = 15

function oneLine(value: unknown): string {
  return String(value ?? "")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 180)
}

/** First useful lines of an output, without "Exited with code" noise. */
function firstMeaningful(body: string): string {
  return body
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean)
    .filter((line) => !/^Exited with code \d+$/i.test(line))
    .slice(0, 3)
    .join(" | ")
}

/** Normalizes a message so equivalent errors share a signature. */
function normalize(text: unknown): string {
  return String(text)
    .toLowerCase()
    .replace(/0x[0-9a-f]+/g, "0x_")
    .replace(/[a-f0-9]{8,}/g, "hex_")
    .replace(/\d+/g, "#")
    .replace(/["'`]{1}[^"'`]{0,200}["'`]{1}/g, "'_'")
    .replace(/[a-z]:\\[^\s"']+/gi, "path_")
    .replace(/\/[^\s"']+/g, "/path_")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 240)
}

function signature(tool: string, message: unknown): string {
  return createHash("sha1")
    .update(`${tool}|${normalize(message)}`)
    .digest("hex")
    .slice(0, 10)
}

function safeInput(input: unknown): string {
  try {
    const text = typeof input === "string" ? input : JSON.stringify(input)
    return oneLine(text)
  } catch {
    return ""
  }
}

/** Extracts the failure from the event, whether as a hard error or as an exit code. */
function detectFailure(event: any): { message: string; exit: number | null } | null {
  if (event?.status === "error") {
    const message = event?.error?.message ?? event?.error?.type ?? "unknown error"
    return { message: String(message), exit: null }
  }

  if (event?.status !== "completed") return null

  const result = event?.result
  const exit = result?.output?.exit ?? result?.metadata?.exit
  if (typeof exit !== "number" || exit === 0) return null

  const texts = Array.isArray(result?.content)
    ? result.content.map((part: any) => part?.text).filter((text: any) => typeof text === "string")
    : []
  const body = `${result?.output?.output ?? ""}\n${texts.join("\n")}`
  const message = firstMeaningful(body) || `output with code ${exit}`
  return { message, exit }
}

/** Rebuilds the recurrent-errors digest in auto.md (only if it changed). */
async function regenerateAuto(): Promise<void> {
  let raw = ""
  try {
    raw = await readFile(JSONL, "utf8")
  } catch {
    return
  }

  const bySig = new Map<
    string,
    { tool: string; error: string; count: number; last: string; project: string }
  >()

  for (const line of raw.split(/\r?\n/)) {
    if (!line) continue
    let record: any
    try {
      record = JSON.parse(line)
    } catch {
      continue
    }
    if (!record?.signature) continue
    const current = bySig.get(record.signature) ?? {
      tool: record.tool ?? "?",
      error: record.error ?? "",
      count: 0,
      last: "",
      project: "",
    }
    current.count += 1
    if ((record.ts ?? "") >= current.last) {
      current.last = record.ts ?? ""
      current.tool = record.tool ?? "?"
      current.error = record.error ?? ""
      current.project = record.project ?? ""
    }
    bySig.set(record.signature, current)
  }

  const top = [...bySig.values()]
    .sort((a, b) => b.count - a.count || (a.last < b.last ? 1 : -1))
    .slice(0, MAX_AUTO)

  const body =
    "<!-- Generated by error-memory. Do not edit by hand. -->\n" +
    "# Recurring errors (auto)\n\n" +
    (top.length
      ? top.map((e) => `- x${e.count} - \`${e.tool}\` - ${e.error}`).join("\n")
      : "- (no recorded errors)") +
    "\n"

  let previous = ""
  try {
    previous = await readFile(AUTO, "utf8")
  } catch {
    /* did not exist */
  }
  if (previous !== body) await writeFile(AUTO, body, "utf8")
}

export default {
  id: "orquestador.error-memory",

  async setup(ctx: any) {
    if (typeof ctx?.tool?.hook !== "function") return

    const project: string = ctx?.location?.directory ?? process.cwd()
    const projectName = path.basename(project)
    const lastInput = new Map<string, unknown>()

    let queue: Promise<unknown> = Promise.resolve()
    const enqueue = (task: () => Promise<void>) => {
      queue = queue.then(task).catch(() => {})
      return queue
    }

    await ctx.tool.hook("execute.before", (event: any) => {
      try {
        if (event?.tool) lastInput.set(event.tool, event.input)
      } catch {
        /* ignore */
      }
    })

    await ctx.tool.hook("execute.after", (event: any) => {
      const failure = detectFailure(event)
      if (!failure) return

      const tool: string = event?.tool ?? "?"
      const input = event?.input ?? lastInput.get(tool)

      void enqueue(async () => {
        try {
          await mkdir(STORE, { recursive: true })

          const record = {
            ts: new Date().toISOString(),
            project,
            projectName,
            tool,
            agent: event?.agent ?? null,
            sessionID: event?.sessionID ?? null,
            exit: failure.exit,
            signature: signature(tool, failure.message),
            input: safeInput(input),
            error: oneLine(failure.message),
          }
          await appendFile(JSONL, JSON.stringify(record) + "\n", "utf8")
          await regenerateAuto()
        } catch {
          /* never break the session because of memory */
        }
      })
    })
  },
}
